"""## 12. RNN, LSTM, GRU and BiLSTM architectures

To keep the baseline comparison fair, all four networks use:
- the same input features,
- the same sequence length,
- the same hidden size,
- the same optimizer,
- the same learning rate,
- the same epoch limit,
- early stopping based on validation loss.
"""

# ============================================================
# Recurrent model definition
# ============================================================

class RecurrentRegressor(nn.Module):
    def __init__(
        self,
        input_size,
        hidden_size=64,
        num_layers=1,
        model_type="LSTM",
        bidirectional=False,
        dropout=0.0
    ):
        super().__init__()

        self.model_type = model_type
        self.bidirectional = bidirectional

        rnn_dropout = dropout if num_layers > 1 else 0.0

        if model_type == "RNN":
            self.recurrent = nn.RNN(
                input_size=input_size,
                hidden_size=hidden_size,
                num_layers=num_layers,
                batch_first=True,
                dropout=rnn_dropout,
                bidirectional=bidirectional
            )

        elif model_type == "LSTM":
            self.recurrent = nn.LSTM(
                input_size=input_size,
                hidden_size=hidden_size,
                num_layers=num_layers,
                batch_first=True,
                dropout=rnn_dropout,
                bidirectional=bidirectional
            )

        elif model_type == "GRU":
            self.recurrent = nn.GRU(
                input_size=input_size,
                hidden_size=hidden_size,
                num_layers=num_layers,
                batch_first=True,
                dropout=rnn_dropout,
                bidirectional=bidirectional
            )

        else:
            raise ValueError("model_type must be RNN, LSTM, or GRU")

        direction_multiplier = 2 if bidirectional else 1

        self.head = nn.Sequential(
            nn.Linear(hidden_size * direction_multiplier, 32),
            nn.ReLU(),
            nn.Linear(32, 1)
        )

    def forward(self, x):

        if self.model_type == "LSTM":
            out, (h_n, c_n) = self.recurrent(x)
        else:
            out, h_n = self.recurrent(x)

        if self.bidirectional:
            # Combine final forward and backward hidden states
            final_hidden = torch.cat(
                (h_n[-2], h_n[-1]),
                dim=1
            )
        else:
            final_hidden = h_n[-1]

        return self.head(final_hidden)

# ============================================================
# Training and prediction helpers
# ============================================================

def train_dl_model(
    model,
    train_loader,
    val_loader,
    epochs=8,
    lr=1e-3,
    patience=2
):
    criterion = nn.MSELoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=lr)

    history = {"train_loss": [], "val_loss": []}

    best_val_loss = float("inf")
    best_state = copy.deepcopy(model.state_dict())
    wait = 0

    start_time = time.perf_counter()

    for epoch in range(1, epochs + 1):
        # ---- Train ----
        model.train()
        train_loss_sum = 0.0

        for xb, yb in train_loader:
            xb = xb.to(DEVICE, non_blocking=True)
            yb = yb.to(DEVICE, non_blocking=True)

            optimizer.zero_grad()
            pred = model(xb)
            loss = criterion(pred, yb)
            loss.backward()
            optimizer.step()

            train_loss_sum += loss.item() * xb.size(0)

        train_loss = train_loss_sum / len(train_loader.dataset)

        # ---- Validate ----
        model.eval()
        val_loss_sum = 0.0

        with torch.no_grad():
            for xb, yb in val_loader:
                xb = xb.to(DEVICE, non_blocking=True)
                yb = yb.to(DEVICE, non_blocking=True)

                pred = model(xb)
                loss = criterion(pred, yb)
                val_loss_sum += loss.item() * xb.size(0)

        val_loss = val_loss_sum / len(val_loader.dataset)

        history["train_loss"].append(train_loss)
        history["val_loss"].append(val_loss)

        print(
            f"Epoch {epoch:02d} | "
            f"Train Loss: {train_loss:.5f} | "
            f"Val Loss: {val_loss:.5f}"
        )

        # Early stopping
        if val_loss < best_val_loss - 1e-6:
            best_val_loss = val_loss
            best_state = copy.deepcopy(model.state_dict())
            wait = 0
        else:
            wait += 1
            if wait >= patience:
                print("Early stopping triggered.")
                break

    training_time = time.perf_counter() - start_time
    model.load_state_dict(best_state)

    return model, history, training_time


def predict_dl(model, loader):
    model.eval()
    preds = []
    actuals = []

    start_time = time.perf_counter()

    with torch.no_grad():
        for xb, yb in loader:
            xb = xb.to(DEVICE, non_blocking=True)
            pred = model(xb).cpu().numpy().ravel()

            preds.append(pred)
            actuals.append(yb.numpy().ravel())

    inference_time = time.perf_counter() - start_time

    return (
        np.concatenate(actuals),
        np.concatenate(preds),
        inference_time
    )

