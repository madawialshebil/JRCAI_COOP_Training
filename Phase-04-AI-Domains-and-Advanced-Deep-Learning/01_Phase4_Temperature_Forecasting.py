def scale_split(split_df):
    X_scaled = feature_scaler.transform(split_df[FEATURES]).astype(np.float32)
    y_scaled = target_scaler.transform(split_df[[TARGET]]).astype(np.float32).ravel()
    return X_scaled, y_scaled

